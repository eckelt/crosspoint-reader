#!/usr/bin/env python3
"""Builds src/deskleaf/FreeDayArtData.cpp from deskleaf-display's motif.

The motif (272x578, three 1-bit layers) was drawn for the 5.79" panel, whose
edges cut it. For the wider X4 Pro screen the black layer is widened by
EXTEND px per side: each row continues the dot density found at its edge and
thins it out outwards, so the sky dissolves into the paper. The frame lines
at the top and bottom are dropped. Output is deterministic.

Usage: deskleaf_freeday_art.py <deskleaf-display>/include/terry_moore_rle.h
"""
import re
import sys

W, H, EXTEND, WINDOW = 272, 578, 72, 14
NW = W + 2 * EXTEND


def noise(x, y, seed):
    v = (x * 374761393 + y * 668265263 + seed * 2246822519) & 0xFFFFFFFF
    v = ((v ^ (v >> 13)) * 1274126177) & 0xFFFFFFFF
    return (v ^ (v >> 16)) & 0xFF


def load(src, name):
    m = re.search(r'terry_moore_%s_rle\[\] PROGMEM = \{(.*?)\};' % name, src, re.S)
    data = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]{2}', m.group(1))]
    raw = bytearray()
    for i in range(0, len(data) - 1, 2):
        raw += bytes([data[i + 1]]) * data[i]
    raw = raw[:W * H // 8].ljust(W * H // 8, b'\0')
    return [[(raw[y * W // 8 + x // 8] >> (7 - x % 8)) & 1 for x in range(W)] for y in range(H)]


def widen_black(b):
    for y in list(range(0, 3)) + list(range(H - 4, H)):
        b[y] = [0] * W  # frame lines

    def density(y, xs):
        ys = range(max(0, y - 10), min(H, y + 11))
        v = sum(b[yy][x] for yy in ys for x in xs) / (len(ys) * len(xs))
        return v if v >= 0.1 else 0  # ignore single outlines

    out = []
    for y in range(H):
        left, right = density(y, range(WINDOW)), density(y, range(W - WINDOW, W))
        row = [0] * EXTEND + b[y] + [0] * EXTEND
        for d in range(1, EXTEND + 1):
            k = (1 - d / EXTEND) ** 1.5
            if noise(EXTEND - d, y, 1) < 256 * left * k:
                row[EXTEND - d] = 1
            if noise(EXTEND + W - 1 + d, y, 2) < 256 * right * k:
                row[EXTEND + W - 1 + d] = 1
        out.append(row)
    return out


def rle(layer):
    raw = bytearray()
    for row in layer:
        for x in range(0, NW, 8):
            raw.append(sum(bit << (7 - i) for i, bit in enumerate(row[x:x + 8])))
    out, i = [], 0
    while i < len(raw):
        n = 1
        while i + n < len(raw) and raw[i + n] == raw[i] and n < 255:
            n += 1
        out += [n, raw[i]]
        i += n
    return out


def emit(name, data):
    lines = [f'const size_t epd_bitmap_terry_moore_{name}_rle_len = {len(data)};',
             f'const unsigned char epd_bitmap_terry_moore_{name}_rle[] = {{']
    for i in range(0, len(data), 16):
        lines.append('  ' + ', '.join(f'0x{v:02X}' for v in data[i:i + 16]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    src = open(sys.argv[1], encoding='utf-8').read()
    layers = {n: load(src, n) for n in ('black', 'red', 'yellow')}
    layers['black'] = widen_black(layers['black'])
    for n in ('red', 'yellow'):
        layers[n] = [[0] * EXTEND + r + [0] * EXTEND for r in layers[n]]
    parts = [
        '// Generated by scripts/deskleaf_freeday_art.py from deskleaf-display',
        '// include/terry_moore_rle.h. Do not edit by hand.',
        f'// Three {NW}x{H} 1-bit layers (black, red, yellow of the 4-color panel),',
        '// each byte-RLE as (count, packed 8-pixel byte) pairs.',
        '#include "FreeDayArt.h"', '', '#if DESKLEAF_CALENDAR', '', 'namespace deskleaf::art {',
    ]
    for n in ('black', 'red', 'yellow'):
        parts.append(emit(n, rle(layers[n])))
    parts += ['}  // namespace deskleaf::art', '', '#endif  // DESKLEAF_CALENDAR', '']
    open('src/deskleaf/FreeDayArtData.cpp', 'w', encoding='utf-8').write('\n'.join(parts))


if __name__ == '__main__':
    main()
